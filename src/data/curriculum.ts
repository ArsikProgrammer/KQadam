export function topicsByGrade(grade: Grade): Topic[] {
  return topics.filter((topic) => topic.grade === grade);
}

/** Темы, которые напрямую опираются на данную (пробел в ней ломает их в первую очередь). */
export function dependentsOf(id: string): Topic[] {
  return topics.filter((topic) => topic.prerequisites.includes(id));
}

/** Все предшественники темы по цепочкам (для оценки глубины пробела). */
export function prerequisiteClosure(id: string): Topic[] {
  const seen = new Set<string>();
  const queue = [...(topicById.get(id)?.prerequisites ?? [])];
  while (queue.length > 0) {
    const current = queue.pop() as string;
    if (seen.has(current)) continue;
    seen.add(current);
    queue.push(...(topicById.get(current)?.prerequisites ?? []));
  }
  return [...seen].map((topicId) => topicById.get(topicId) as Topic);
}
